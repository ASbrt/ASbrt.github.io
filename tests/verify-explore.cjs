// With Vite running: NODE_PATH=<directory containing playwright> node tests/verify-explore.cjs
const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.addInitScript(() => {
      Object.defineProperty(navigator, 'clipboard', { value: { writeText: async text => { window.copiedLink = text } } })
    })
    await page.goto('http://127.0.0.1:5173/?seed=42&gen=2')
    for (const width of [1280, 390, 320]) {
      await page.setViewportSize({ width, height: 900 })
      const layout = await page.evaluate(() => {
        const buttons = document.querySelector('.hero__heading .sculpture-actions').getBoundingClientRect()
        const divider = document.querySelector('.hero__meta').getBoundingClientRect()
        const title = document.querySelector('h1').getBoundingClientRect()
        return { above: buttons.bottom <= divider.top, aligned: Math.abs(buttons.right - divider.right) < 2, fits: buttons.left >= 0 && buttons.right <= innerWidth, clear: buttons.left >= title.right || buttons.top >= title.bottom }
      })
      assert.deepEqual(layout, { above: true, aligned: true, fits: true, clear: true }, `Browsing controls fit at ${width}px`)
      await page.screenshot({ path: `/tmp/sculpture-browse-${width}.png` })
    }
    await page.setViewportSize({ width: 1280, height: 900 })
    const canvas = page.locator('canvas.shader-canvas')
    // Compare the artwork away from overlaid controls and focus outlines.
    const shot = () => page.screenshot({ clip: { x: 5, y: 180, width: page.viewportSize().width - 10, height: page.viewportSize().height - 430 } })
    const share = page.getByRole('button', { name: '↗ Share', exact: true })
    await share.click()
    const seedLink = await page.evaluate(() => window.copiedLink)
    await page.getByRole('button', { name: 'Explore sculpture', exact: true }).click()
    assert.equal(await canvas.evaluate(el => el === document.activeElement), true)
    assert.equal(await page.locator('.hero__content').evaluate(el => el.inert), true)
    console.log('Checking keyboard and share')
    const original = await shot()
    await page.keyboard.press('ArrowRight')
    assert.equal((await shot()).equals(original), false, 'Keyboard rotation changes the render')
    await share.click()
    assert.equal(await page.evaluate(() => window.copiedLink), seedLink, 'Exploring preserves the seed link')
    await page.getByRole('button', { name: 'Reset view' }).click()
    assert.equal((await shot()).equals(original), true, 'Reset restores the original view')

    console.log('Checking movement and reset')
    await canvas.focus()
    await page.keyboard.press('Shift+ArrowRight')
    assert.equal((await shot()).equals(original), false, 'Shift+arrow moves the artwork')
    await share.click()
    assert.equal(await page.evaluate(() => window.copiedLink), seedLink, 'Moving preserves the seed link')
    await page.getByRole('button', { name: 'Reset view' }).click()
    assert.equal((await shot()).equals(original), true, 'Reset restores position')
    await page.getByRole('button', { name: 'Move', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Move', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.mouse.move(640, 300)
    await page.mouse.down()
    await page.mouse.move(720, 360, { steps: 4 })
    await page.mouse.up()
    const moved = await shot()
    assert.equal(moved.equals(original), false, 'Move mode drag repositions the sculpture')
    await page.getByRole('button', { name: 'Reset view' }).click()
    assert.equal((await shot()).equals(original), true)
    await page.getByRole('button', { name: 'Rotate', exact: true }).click()
    await page.keyboard.down('Shift')
    await page.mouse.move(640, 300)
    await page.mouse.down()
    await page.mouse.move(720, 360, { steps: 4 })
    await page.mouse.up()
    await page.keyboard.up('Shift')
    assert.equal((await shot()).equals(moved), true, 'Shift-drag matches Move mode')
    await page.getByRole('button', { name: 'Reset view' }).click()

    console.log('Checking pointer and zoom')
    await page.mouse.move(640, 300)
    await page.mouse.down()
    await page.mouse.move(760, 350, { steps: 5 })
    await page.mouse.up()
    assert.equal((await shot()).equals(original), false, 'Pointer drag rotates')
    await page.keyboard.press('Home')
    assert.equal((await shot()).equals(original), true)
    await page.mouse.wheel(0, -160)
    const zoomed = await shot()
    assert.equal(zoomed.equals(original), false, 'Wheel zoom changes the render')
    assert.equal(await page.evaluate(() => window.scrollY), 0, 'Active wheel does not scroll the page')
    for (let i = 0; i < 30; i++) await page.keyboard.press('+')
    const maximumZoom = await shot()
    await page.keyboard.press('+')
    assert.equal((await shot()).equals(maximumZoom), true, 'Zoom is bounded')
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('button', { name: 'Explore sculpture', exact: true }).evaluate(el => el === document.activeElement), true)
    assert.equal(await page.locator('.hero__content').evaluate(el => el.inert), false)
    await page.mouse.wheel(0, 600)
    await page.waitForFunction(() => window.scrollY > 0)
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.getByRole('button', { name: 'Explore sculpture', exact: true }).click()
    await page.getByRole('button', { name: '↝ New sculpture', exact: true }).click()
    const newView = await shot()
    await page.getByRole('button', { name: 'Reset view' }).click()
    assert.equal((await shot()).equals(newView), true, 'New sculpture resets visitor offsets')
    await page.getByRole('button', { name: 'Done', exact: true }).click()

    // Touch pointers exercise the same handler used on phones, including cancellation.
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Explore sculpture', exact: true }).click()
    const mobileOriginal = await shot()
    await canvas.evaluate(el => {
      // Synthetic pointers cannot be captured by the browser.
      el.setPointerCapture = () => {}
      const send = (type, pointerId, clientX) => el.dispatchEvent(new PointerEvent(type, { pointerId, pointerType: 'touch', button: 0, clientX, clientY: 350, bubbles: true }))
      send('pointerdown', 10, 100)
      send('pointerdown', 11, 200)
      send('pointermove', 11, 260)
      send('pointercancel', 10, 100)
      send('pointerup', 11, 260)
    })
    assert.equal((await shot()).equals(mobileOriginal), false, 'Pinch zoom changes the render')
    await page.getByRole('button', { name: 'Reset view' }).click()
    assert.equal((await shot()).equals(mobileOriginal), true)
    await page.screenshot({ path: '/tmp/sculpture-explore-mobile.png' })
    // Exercise Lenis and the animated renderer, which reduced-motion mode bypasses.
    const animated = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    animated.on('pageerror', e => errors.push(e.message))
    await animated.goto('http://127.0.0.1:5173/?seed=42&gen=2')
    // Finish the initial entrance before checking the independent Explore transition.
    await animated.waitForFunction(() => Number(getComputedStyle(document.querySelector('.hero__meta')).opacity) === 1)
    await animated.getByRole('button', { name: 'Explore sculpture', exact: true }).click()
    assert.equal(await animated.locator('.hero__content').evaluate(el => getComputedStyle(el).transitionDuration), '0.4s, 0.3s')
    await animated.waitForFunction(() => getComputedStyle(document.querySelector('.hero__content')).opacity === '0')
    await animated.mouse.move(640, 300)
    await animated.mouse.wheel(0, 300)
    await animated.screenshot({ path: '/tmp/sculpture-explore-desktop.png' })
    assert.equal(await animated.evaluate(() => window.scrollY), 0, 'Lenis leaves the active sculpture wheel alone')
    await animated.keyboard.press('Escape')
    await animated.waitForFunction(() => getComputedStyle(document.querySelector('.hero__content')).opacity === '1')
    await animated.mouse.wheel(0, 600)
    await animated.waitForFunction(() => window.scrollY > 100)
    const fallback = await browser.newPage()
    await fallback.addInitScript(() => { HTMLCanvasElement.prototype.getContext = () => null })
    await fallback.goto('http://127.0.0.1:5173/')
    await fallback.locator('.shader-canvas--fallback').waitFor()
    assert.equal(await fallback.getByRole('button', { name: 'Explore sculpture', exact: true }).count(), 0, 'No Explore control when WebGL is unavailable')
    assert.deepEqual(errors, [], 'No runtime errors')
    console.log('Explore checks passed: transitions, keyboard, movement, drag, wheel, pinch, limits, reset, focus, scrolling, share, and new sculpture.')
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
